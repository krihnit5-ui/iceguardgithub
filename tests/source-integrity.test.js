import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const root=path.join(here,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const features=fs.readFileSync(path.join(root,'features.js'),'utf8');
const science=fs.readFileSync(path.join(root,'science-data.js'),'utf8');
const ai=fs.readFileSync(path.join(root,'ai-engine.js'),'utf8');
const decision=fs.readFileSync(path.join(root,'decision-support.js'),'utf8');
const all=html+features+science+ai+decision;
assert(!/SIH26059|SIH tools|SIMULATED DEMO DATA/i.test(all),'hackathon-specific branding should be removed from the product UI');
assert(!/Math\.random|synthetic concentration|Synthetic grid|simulated sensor feed|risk index by site/i.test(all),'synthetic scientific data UI should not be present');
assert(html.includes('Open-Meteo forecast model'),'weather model source must be identified');
assert(html.includes('NSIDC Sea Ice Index'),'sea-ice extent source must be identified');
assert(html.includes('NOAA S-NPP VIIRS'),'spatial sea-ice concentration source must be identified');
assert(html.includes('Historical trajectory data and modelled forecasts are kept visually separate from observations.'),'observed/modelled separation must be explicit');
assert(html.includes('certified navigation systems'),'navigation decision-support boundary must be explicit');
assert(ai.includes('k-nearest-neighbour anomaly detection') || ai.includes('kNN'),'anomaly model must be present');
assert(ai.includes('POLYNOMIAL_REGRESSION_DEGREE_2') && ai.includes('MODELLED_NOT_OBSERVED'),'trajectory ML model must be labelled');
assert(ai.includes('MODEL_NOT_TRAINED') && ai.includes('INSUFFICIENT_DATA'),'trajectory model must fail closed when untrained or data is missing');
assert(ai.includes('interpolationSteps') && ai.includes('DECISION_SUPPORT_ONLY'),'route DSS must sample full segments and preserve decision-support boundary');
for(const id of ['map3d','mapStatus','feedNote','sA','sW','sL','sT','cLine','cBar','refreshWeather','extentStatus','extentValue','extentDate','extentMetric','extentMetricNote','retryExtent','bergNote','bergList','proxList','proxStatus','routeResult','optimizeRoute','aiStatus','aiList','iceConcMap']) assert(html.includes(`id="${id}"`),`missing DOM id ${id}`);
console.log('PASS: source attribution, observed/modelled separation, AI layer, spatial sea-ice layer and route-DSS boundaries are present.');
